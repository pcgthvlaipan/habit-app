const TABLES = { en: EN, th: TH };

function lookup(table, path) {
  return path.split(".").reduce((o, k) => (o == null ? o : o[k]), table);
}

function interpolate(str, vars) {
  if (!vars || typeof str !== "string") return str;
  return str.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

const LanguageContext = createContext({ lang: "th", setLang: () => {}, t: (k) => k });

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try {
      const stored = localStorage.getItem(STORE_KEY);
      if (stored === "en" || stored === "th") return stored;
    } catch { /* private mode / disabled storage */ }
    return "th";
  });

  useEffect(() => {
    try { localStorage.setItem(STORE_KEY, lang); } catch { /* ignore */ }
    try { document.documentElement.lang = lang; } catch { /* ignore */ }
  }, [lang]);

  const value = useMemo(() => {
    function t(key, vars) {
      const raw = lookup(TABLES[lang], key);
      const fallback = raw == null ? lookup(TABLES.en, key) : raw;
      return interpolate(fallback == null ? key : fallback, vars);
    }
    return { lang, setLang: setLangState, t };
  }, [lang]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

// eslint-disable-next-line react-refresh/only-export-components
export function useT() {
  return useContext(LanguageContext);
}
